# Check_MyMediaInv.ps1
# Version 1.3.1 - My Media for Alexa inventory and README generator
# Preview by default. -Execute creates documentation, never modifies recordings.
[CmdletBinding()]
param(
    [string]$Root = 'D:\BU\MyMedia\Recordings',
    [string]$Library = 'D:\BU\MyMedia\Library',
    [switch]$Execute
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$extensions = @('.mp3','.flac','.wav','.m4a','.wma','.ogg','.aac')
$marker = '<!-- Generated by Get-MyMediaInventory.ps1 v1.2; edits will be overwritten -->'

function Test-IgnoredPath {
    param([string]$Path)
    $parts = $Path -split '[\\/]'
    foreach ($part in $parts) {
        if ($part -in @('Zip', 'Zip Files')) {
            return $true
        }
    }
    return $false
}
function Get-Recordings {
    param([string]$Path)
    @(Get-ChildItem -LiteralPath $Path -Recurse -File |
        Where-Object { $_.Extension.ToLowerInvariant() -in $extensions -and -not (Test-IgnoredPath $_.FullName) })
}
function Get-Count {
    param([object[]]$Items)
    return @($Items).Count
}
function Get-Summary {
    param([string]$Name,[object[]]$Files,[string]$Folder)
    [long]$bytes = 0
    foreach ($f in $Files) { $bytes += [long]$f.Length }
    [pscustomobject]@{
        Name=$Name
        Folders=@(Get-ChildItem -LiteralPath $Folder -Directory -Recurse | Where-Object { -not (Test-IgnoredPath $_.FullName) }).Count
        Recordings=@($Files).Count
        SizeGB=[math]::Round($bytes / 1GB,2)
        Status=$(if (@($Files).Count) {'Active'} else {'Not Populated'})
    }
}
function Escape-Markdown {
    param([string]$Text)
    return ($Text -replace '\|','\|' -replace '\r|\n',' ')
}
function Get-Index {
    param([string]$Base,[object[]]$Files)
    $lines = @('| # | Recording / Relative Filename |','|---:|---|')
    $i = 0
    foreach ($file in @($Files | Sort-Object FullName)) {
        $i++
        $relative = $file.FullName.Substring($Base.Length).TrimStart('\','/')
        $lines += "| $i | $(Escape-Markdown $relative) |"
    }
    if ($i -eq 0) { $lines += '| - | No recordings found |' }
    return $lines
}
function Get-ReadmePath {
    param([string]$Directory)
    $main = Join-Path $Directory 'README.md'
    if (-not (Test-Path -LiteralPath $main)) { return $main }
    if ((Get-Content -LiteralPath $main -TotalCount 1) -eq $marker) { return $main }
    $generated = Join-Path $Directory 'README.generated.md'
    if ((Test-Path -LiteralPath $generated) -and
        (Get-Content -LiteralPath $generated -TotalCount 1) -ne $marker) {
        throw "Refusing to overwrite manual file: $generated"
    }
    return $generated
}
function Save-Text {
    param([string]$Path,[string[]]$Lines)
    if (-not $Execute) { Write-Host "PREVIEW: $Path"; return }
    $parent = Split-Path -Parent $Path
    if (-not (Test-Path -LiteralPath $parent)) {
        New-Item -ItemType Directory -Path $parent -Force | Out-Null
    }
    Set-Content -LiteralPath $Path -Value $Lines -Encoding UTF8
    Write-Host "WROTE: $Path"
}
function Save-Readme {
    param([string]$Directory,[string]$Title,[string[]]$Lines)
    $path = Get-ReadmePath $Directory
    Save-Text -Path $path -Lines (@($marker,"# $Title",'') + $Lines)
}
function Save-Csv {
    param([string]$Path,[object[]]$Rows)
    if (-not $Execute) { Write-Host "PREVIEW: $Path"; return }
    $parent = Split-Path -Parent $Path
    if (-not (Test-Path -LiteralPath $parent)) {
        New-Item -ItemType Directory -Path $parent -Force | Out-Null
    }
    if (@($Rows).Count) {
        $Rows | Export-Csv -LiteralPath $Path -NoTypeInformation -Encoding UTF8
    } else {
        Set-Content -LiteralPath $Path -Value '' -Encoding UTF8
    }
    Write-Host "WROTE: $Path"
}
if (-not (Test-Path -LiteralPath $Root -PathType Container)) {
    throw "Recording directory not found: $Root"
}
$Root = (Resolve-Path -LiteralPath $Root).Path
$categories = @(Get-ChildItem -LiteralPath $Root -Directory |
    Where-Object { $_.Name -notin @('Zip','Zip Files') } | Sort-Object Name)
$summary = @()
$inventory = [System.Collections.Generic.List[object]]::new()
$otrSummary = @()
$otrLibrary = Join-Path $Library 'OTR'
Write-Host $(if ($Execute) {'EXECUTE MODE'} else {'PREVIEW MODE - read only'}) -ForegroundColor Cyan

foreach ($category in $categories) {
    $files = @(Get-Recordings $category.FullName)
    $summary += Get-Summary -Name $category.Name -Files $files -Folder $category.FullName
    foreach ($file in $files) {
        $relative = $file.FullName.Substring($Root.Length).TrimStart('\','/')
        $parts = $relative -split '[\\/]'
        $show = if ($category.Name -eq 'OTR' -and $parts.Count -ge 3) {$parts[1]} else {''}
        $inventory.Add([pscustomobject]@{
            Category=$category.Name; Show=$show; FileName=$file.Name
            RelativePath=$relative; Extension=$file.Extension
            SizeBytes=$file.Length; Modified=$file.LastWriteTime.ToString('yyyy-MM-dd HH:mm:ss')
        })
    }
    if ($category.Name -eq 'OTR') {
        foreach ($show in @(Get-ChildItem -LiteralPath $category.FullName -Directory | Sort-Object Name)) {
            $showFiles = @($files | Where-Object {
                $_.FullName.StartsWith(($show.FullName.TrimEnd('\') + '\'),
                    [StringComparison]::OrdinalIgnoreCase)
            })
            $otrSummary += Get-Summary -Name $show.Name -Files $showFiles -Folder $show.FullName
            $folders = @('| Season / Subfolder | Recordings |','|---|---:|')
            $rootCount = @($showFiles | Where-Object { $_.DirectoryName -eq $show.FullName }).Count
            $folders += "| (Show root) | $rootCount |"
            foreach ($sub in @(Get-ChildItem -LiteralPath $show.FullName -Directory -Recurse | Where-Object { -not (Test-IgnoredPath $_.FullName) } | Sort-Object FullName)) {
                $prefix = $sub.FullName.TrimEnd('\') + '\'
                $count = @($showFiles | Where-Object {
                    $_.FullName.StartsWith($prefix,[StringComparison]::OrdinalIgnoreCase)
                }).Count
                $name = $sub.FullName.Substring($show.FullName.Length).TrimStart('\','/')
                $folders += "| $(Escape-Markdown $name) | $count |"
            }
            $body = @("**Recordings:** $($showFiles.Count)",'','## Season and Subfolder Inventory','') +
                $folders +
                @('','## Research and Documentation','',
                  'Episode titles and original broadcast dates require separate source verification.')
            Save-Readme -Directory (Join-Path $otrLibrary $show.Name) -Title $show.Name -Lines $body
        }
    } else {
        $body = @("**Recordings:** $($files.Count)",'','## Recording Index','') +
            @(Get-Index -Base $category.FullName -Files $files)
        Save-Readme -Directory (Join-Path $Library $category.Name) -Title $category.Name -Lines $body
    }
}
$otrLines = @('| Show | Recordings | Folders |','|---|---:|---:|')
foreach ($show in $otrSummary) {
    $dir = Join-Path $otrLibrary $show.Name
    $readme = Split-Path -Leaf (Get-ReadmePath $dir)
    $urlName = [Uri]::EscapeDataString($show.Name)
    $otrLines += "| [$($show.Name)]($urlName/$readme) | $($show.Recordings) | $($show.Folders) |"
}
Save-Readme -Directory $otrLibrary -Title 'Old Time Radio (OTR)' -Lines $otrLines
$categoryLines = @('| Category | Recordings | Folders |','|---|---:|---:|')
foreach ($row in $summary) {
    $dir = Join-Path $Library $row.Name
    $readme = Split-Path -Leaf (Get-ReadmePath $dir)
    $urlName = [Uri]::EscapeDataString($row.Name)
    $categoryLines += "| [$($row.Name)]($urlName/$readme) | $($row.Recordings) | $($row.Folders) |"
}
$total = 0
foreach ($row in $summary) { $total += [int]$row.Recordings }
$categoryLines += '',"**Total recordings:** $total",'',
    'Zip and Zip Files folders are excluded at every level. Audio remains local.'
Save-Readme -Directory $Library -Title 'MyMedia Library' -Lines $categoryLines
Save-Csv -Path (Join-Path $Library 'MediaInventory.csv') -Rows @($inventory.ToArray())
Save-Csv -Path (Join-Path $otrLibrary 'OTRInventory.csv') -Rows $otrSummary
$summary | Format-Table -AutoSize
$otrSummary | Format-Table -AutoSize
Write-Host "Total recordings: $total"
