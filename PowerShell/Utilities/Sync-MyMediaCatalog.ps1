# Sync-MyMediaCatalog.ps1
# Version 1.1
# Copies reviewed MyMedia inventory Markdown/CSV files into a local Git clone.
# Preview by default. -Execute copies; -Execute -Push also commits and pushes.
# Does not copy audio files, delete destination files, or regenerate inventories.
[CmdletBinding()]
param(
    [string]$Library = 'D:\BU\MyMedia\Library',
    [string]$Repository = 'D:\BU\My_Computer\GitResp\Radio-Hitz',
    [switch]$Execute,
    [switch]$Push
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

if ($Push -and -not $Execute) {
    throw 'Use -Execute -Push together. -Push alone is not allowed.'
}
if (-not (Test-Path -LiteralPath $Library -PathType Container)) {
    throw "Library not found: $Library"
}
if (-not (Test-Path -LiteralPath $Repository -PathType Container)) {
    throw "Repository not found: $Repository. Clone the GitHub repository first."
}

$Library = (Resolve-Path -LiteralPath $Library).Path.TrimEnd('\','/')
$Repository = (Resolve-Path -LiteralPath $Repository).Path.TrimEnd('\','/')
$gitFolder = Join-Path $Repository '.git'
if (-not (Test-Path -LiteralPath $gitFolder)) {
    throw "Not a local Git repository: $Repository"
}
if (-not (Get-Command git -ErrorAction SilentlyContinue)) {
    throw 'Git for Windows is required and must be on PATH.'
}

function Invoke-Git {
    param([string[]]$Arguments)
    $output = & git -C $Repository @Arguments 2>&1
    if ($LASTEXITCODE -ne 0) {
        throw "git $($Arguments -join ' ') failed: $($output -join [Environment]::NewLine)"
    }
    return @($output)
}

$remote = @(Invoke-Git -Arguments @('remote','get-url','origin')) -join ''
if ($remote -notmatch '(?i)(github\.com[:/])goaskchaz/Radio_Hitz(\.git)?$') {
    throw "Unexpected origin remote: $remote. Expected goaskchaz/Radio_Hitz."
}
$branch = @(Invoke-Git -Arguments @('branch','--show-current')) -join ''
if ($branch -ne 'main') {
    throw "Checkout the main branch first (current branch: $branch)."
}

# Only README.md / README.generated.md and the two generated CSVs are eligible.
# Reject symlinks/reparse points and excluded ZIP directories.
$files = @(Get-ChildItem -LiteralPath $Library -File -Recurse | Where-Object {
    $_.Name -in @('README.md','README.generated.md','MediaInventory.csv','OTRInventory.csv') -and
    ($_.FullName.Substring($Library.Length).TrimStart('\','/') -split '[\\/]') -notcontains 'Zip' -and
    ($_.FullName.Substring($Library.Length).TrimStart('\','/') -split '[\\/]') -notcontains 'Zip Files' -and
    -not ($_.Attributes -band [IO.FileAttributes]::ReparsePoint)
} | Sort-Object FullName)

$manifest = [System.Collections.Generic.List[object]]::new()
foreach ($file in $files) {
    $relative = $file.FullName.Substring($Library.Length).TrimStart('\','/')
    $segments = $relative -split '[\\/]'
    if ($segments.Count -gt 1) {
        $folder = $Library
        $skip = $false
        foreach ($segment in $segments[0..($segments.Count-2)]) {
            $folder = Join-Path $folder $segment
            if ((Get-Item -LiteralPath $folder).Attributes -band [IO.FileAttributes]::ReparsePoint) {
                $skip = $true
                break
            }
        }
        if ($skip) { continue }
    }
    # Generated README files must carry the script's marker.
    if ($file.Extension -eq '.md') {
        $firstLine = Get-Content -LiteralPath $file.FullName -TotalCount 1
        if ($firstLine -notmatch '^<!-- Generated by Get-MyMediaInventory\.ps1 v1\.2; edits will be overwritten -->$') {
            Write-Warning "Skipping README without expected generated marker: $relative"
            continue
        }
    }
    # Do not publish a catalog that contains an absolute local path.
    $textContent = Get-Content -LiteralPath $file.FullName -Raw
    if ($textContent -match '(?i)[A-Z]:\\|\\\\[^\\\s]+\\[^\\\s]+') {
        Write-Warning "Skipping catalog with an absolute local or UNC path: $relative"
        continue
    }
    $destination = Join-Path (Join-Path $Repository 'Catalog') $relative
    $state = 'New'
    if (Test-Path -LiteralPath $destination) {
        $same = (Get-FileHash -LiteralPath $file.FullName -Algorithm SHA256).Hash -eq
                (Get-FileHash -LiteralPath $destination -Algorithm SHA256).Hash
        $state = if ($same) { 'Unchanged' } else { 'Update' }
    }
    $manifest.Add([pscustomobject]@{
        Status=$state; Source=$file.FullName; Destination=$destination
        RelativePath=('Catalog/' + ($relative -replace '\\','/'))
    })
}

$manifest | Select-Object Status,RelativePath | Format-Table -AutoSize
$pending = @($manifest | Where-Object { $_.Status -ne 'Unchanged' })
Write-Host "Catalog files: $($manifest.Count); proposed changes: $($pending.Count)"
if (-not $Execute) {
    Write-Host 'PREVIEW ONLY: No files copied, committed, or pushed.' -ForegroundColor Cyan
    return
}
if ($pending.Count -eq 0) {
    Write-Host 'No catalog changes to copy.'
    return
}

# Avoid overwriting changes in the clone, including changes outside Catalog.
$dirty = @(Invoke-Git -Arguments @('status','--porcelain'))
if ($dirty.Count -gt 0) {
    throw 'Git working tree has changes. Commit, stash, or discard them before -Execute.'
}
foreach ($entry in $pending) {
    $parent = Split-Path -Parent $entry.Destination
    if (-not (Test-Path -LiteralPath $parent)) {
        New-Item -Path $parent -ItemType Directory -Force | Out-Null
    }
    Copy-Item -LiteralPath $entry.Source -Destination $entry.Destination -Force
    Write-Host "COPIED: $($entry.RelativePath)"
}
if (-not $Push) {
    Write-Host 'Files copied to the local clone. Review with git diff and git status.'
    Write-Host 'Nothing has been committed or pushed.'
    return
}

# Stage only files that this invocation copied.
foreach ($entry in $pending) {
    Invoke-Git -Arguments @('add','--',$entry.RelativePath) | Out-Null
}
$staged = @(Invoke-Git -Arguments @('diff','--cached','--name-only'))
if ($staged.Count -eq 0) {
    Write-Host 'No staged changes to commit.'
    return
}
Invoke-Git -Arguments @('commit','-m','Update reviewed MyMedia catalog indexes') | Out-Null
Invoke-Git -Arguments @('push','origin','main') | Out-Null
Write-Host 'Committed and pushed catalog changes to origin/main.' -ForegroundColor Green
